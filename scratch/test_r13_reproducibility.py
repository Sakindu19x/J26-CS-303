"""R13 Reproducibility Test: Delete processed data, rerun pipelines, compare SHA-256 hashes."""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

processed_dir = Path("data/processed")
reports_dir = Path("reports")

# Target JSON files to compare
processed_targets = [
    "attack_sequences.json",
    "attack_timelines.json",
    "loeo_folds.json",
    "next_technique_samples.json",
    "normalized_events.json",
    "technique_tactic_reference.json",
]

report_targets = [
    "data_quality_report.json",
    "timeline_validation_report.json",
    "tactic_discrepancy_report.json",
    "sequence_statistics.json",
]

def hash_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        while chunk := f.read(1024 * 1024):
            h.update(chunk)
    return h.hexdigest()

# 1. Record baseline hashes
baseline_hashes = {}
for name in processed_targets:
    p = processed_dir / name
    if p.is_file():
        baseline_hashes[f"data/processed/{name}"] = hash_file(p)

for name in report_targets:
    p = reports_dir / name
    if p.is_file():
        baseline_hashes[f"reports/{name}"] = hash_file(p)

print("Baseline Hashes:")
for k, v in baseline_hashes.items():
    print(f"  {k}: {v}")

# 2. Delete processed and generated report files
for name in processed_targets:
    p = processed_dir / name
    if p.is_file():
        p.unlink()

for p in processed_dir.glob("*.csv"):
    p.unlink()

for name in report_targets:
    p = reports_dir / name
    if p.is_file():
        p.unlink()

# also delete markdown reports generated by pipeline
for name in [
    "data_quality_report.md",
    "timeline_validation_report.md",
    "tactic_discrepancy_report.md",
    "sequence_statistics.md",
]:
    p = reports_dir / name
    if p.is_file():
        p.unlink()

print("Deleted processed and generated report files. Verifying deletion...")
assert not any((processed_dir / name).is_file() for name in processed_targets)
assert not any((reports_dir / name).is_file() for name in report_targets)

# 3. Rerun documented pipelines in order
py_bin = sys.executable
cmds = [
    [py_bin, "scripts/run_normalization.py"],
    [py_bin, "scripts/run_timeline_pipeline.py"],
    [py_bin, "scripts/run_samples_and_stats.py"],
]

for cmd in cmds:
    print(f"Running: {' '.join(cmd)}...")
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"FAILED: {cmd}\nSTDOUT:\n{res.stdout}\nSTDERR:\n{res.stderr}")
        sys.exit(1)

# 4. Hash regenerated files and compare
regenerated_hashes = {}
comparison = {}
all_matched = True

all_targets = [("data/processed", name) for name in processed_targets] + [("reports", name) for name in report_targets]

for folder, name in all_targets:
    p = Path(folder) / name
    assert p.is_file(), f"Regenerated file missing: {p}"
    key = f"{folder}/{name}"
    new_h = hash_file(p)
    regenerated_hashes[key] = new_h
    match = (new_h == baseline_hashes[key])
    if not match:
        all_matched = False
    comparison[key] = {
        "baseline": baseline_hashes[key],
        "regenerated": new_h,
        "match": match,
    }

print("\nR13 Comparison Result:")
print(json.dumps(comparison, indent=2))
print(f"\nALL PROCESSED AND REPORT JSON HASHES MATCH: {all_matched}")

if not all_matched:
    sys.exit(1)
